BEGIN IMMEDIATE;
CREATE TABLE sources(id INTEGER PRIMARY KEY, path TEXT NOT NULL UNIQUE, available INTEGER NOT NULL, generation INTEGER NOT NULL DEFAULT 0);
CREATE TABLE artists(id INTEGER PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE albums(id INTEGER PRIMARY KEY, identity TEXT NOT NULL UNIQUE, title TEXT NOT NULL, artist_id INTEGER NOT NULL REFERENCES artists);
CREATE TABLE editions(id INTEGER PRIMARY KEY, album_id INTEGER NOT NULL UNIQUE REFERENCES albums, folder TEXT NOT NULL);
CREATE TABLE tracks(id INTEGER PRIMARY KEY, edition_id INTEGER NOT NULL REFERENCES editions, metadata TEXT NOT NULL, cover TEXT);
CREATE TABLE files(id INTEGER PRIMARY KEY, source_id INTEGER NOT NULL REFERENCES sources, path TEXT NOT NULL, track_id INTEGER NOT NULL UNIQUE REFERENCES tracks, size INTEGER NOT NULL, modified TEXT NOT NULL, seen INTEGER NOT NULL, available INTEGER NOT NULL, UNIQUE(source_id,path));
CREATE INDEX files_source_seen ON files(source_id,seen);
CREATE INDEX tracks_edition ON tracks(edition_id);
PRAGMA user_version=1;
COMMIT;
