use rap_core::config::Language;

#[derive(Clone, Copy)]
pub enum Text {
    Play,
    Pause,
    Stop,
    Previous,
    Next,
    Shuffle,
    Repeat,
    Volume,
    SeekBack,
    SeekForward,
    RepeatOff,
    RepeatTrack,
    RepeatAll,
    OpenFile,
    PlaybackError,
    Albums,
    Artists,
    Genres,
    Years,
    Settings,
    AddSource,
    Rescan,
    Cancel,
    Search,
    Empty,
    EmptyHint,
    NoResults,
    Grid,
    List,
    Back,
    Tracks,
    Unavailable,
    Sources,
    RemoveSource,
    ConfirmRemove,
    Language,
    Theme,
    Dark,
    Light,
    French,
    English,
    All,
    Clear,
    Format,
    Year,
    Genre,
    NothingPlaying,
    Scan,
    Errors,
    Cancelled,
    Ready,
    VariousArtists,
    Editions,
    SourceUnavailable,
}

pub fn text(language: Language, key: Text) -> &'static str {
    let (fr, en) = match key {
        Text::Play => ("Lire", "Play"),
        Text::Pause => ("Pause", "Pause"),
        Text::Stop => ("Arrêter", "Stop"),
        Text::Previous => ("Précédente", "Previous"),
        Text::Next => ("Suivante", "Next"),
        Text::Shuffle => ("Aléatoire", "Shuffle"),
        Text::Repeat => ("Répéter", "Repeat"),
        Text::Volume => ("Volume", "Volume"),
        Text::SeekBack => ("−10 s", "−10 s"),
        Text::SeekForward => ("+10 s", "+10 s"),
        Text::RepeatOff => ("Désactivé", "Off"),
        Text::RepeatTrack => ("Piste", "Track"),
        Text::RepeatAll => ("Album", "Album"),
        Text::OpenFile => ("Ouvrir un fichier", "Open file"),
        Text::PlaybackError => ("Erreur", "Error"),
        Text::Albums => ("Albums", "Albums"),
        Text::Artists => ("Artistes", "Artists"),
        Text::Genres => ("Genres", "Genres"),
        Text::Years => ("Années", "Years"),
        Text::Settings => ("Paramètres", "Settings"),
        Text::AddSource => ("Ajouter un dossier", "Add folder"),
        Text::Rescan => ("Actualiser", "Rescan"),
        Text::Cancel => ("Annuler", "Cancel"),
        Text::Search => ("Rechercher dans la bibliothèque…", "Search your library…"),
        Text::Empty => ("Votre musique, tout simplement.", "Your music, simply."),
        Text::EmptyHint => (
            "Ajoutez un dossier pour retrouver vos albums et leurs pochettes.",
            "Add a folder to discover your albums and their artwork.",
        ),
        Text::NoResults => ("Aucun résultat", "No results"),
        Text::Grid => ("Grille", "Grid"),
        Text::List => ("Liste", "List"),
        Text::Back => ("Retour", "Back"),
        Text::Tracks => ("pistes", "tracks"),
        Text::Unavailable => ("Indisponible", "Unavailable"),
        Text::Sources => ("Dossiers sources", "Source folders"),
        Text::RemoveSource => ("Retirer", "Remove"),
        Text::ConfirmRemove => (
            "Retirer de la bibliothèque ? Les fichiers ne seront pas touchés.",
            "Remove from library? Files will not be touched.",
        ),
        Text::Language => ("Langue", "Language"),
        Text::Theme => ("Apparence", "Appearance"),
        Text::Dark => ("Sombre", "Dark"),
        Text::Light => ("Clair", "Light"),
        Text::French => ("Français", "French"),
        Text::English => ("Anglais", "English"),
        Text::All => ("Tous", "All"),
        Text::Clear => ("Effacer les filtres", "Clear filters"),
        Text::Format => ("Format", "Format"),
        Text::Year => ("Année", "Year"),
        Text::Genre => ("Genre", "Genre"),
        Text::NothingPlaying => ("Aucune lecture en cours", "Nothing playing"),
        Text::Scan => ("Analyse", "Scanning"),
        Text::Errors => ("erreurs", "errors"),
        Text::Cancelled => ("Analyse annulée", "Scan cancelled"),
        Text::Ready => ("Prêt", "Ready"),
        Text::VariousArtists => ("Artistes divers", "Various artists"),
        Text::Editions => ("Éditions", "Editions"),
        Text::SourceUnavailable => (
            "source indisponible, son contenu reste affiché",
            "source unavailable, its content stays listed",
        ),
    };
    match language {
        Language::French => fr,
        Language::English => en,
    }
}
