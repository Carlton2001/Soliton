/// `Genre : Jazz` / `Genre: Jazz`, following each language's typography.
pub fn labelled(language: Language, label: &str, value: &str) -> String {
    match language {
        Language::French => format!("{label} : {value}"),
        Language::English => format!("{label}: {value}"),
    }
}

/// `Années 1970` / `1970s`.
pub fn decade(language: Language, decade: u32) -> String {
    match language {
        Language::French => format!("Années {decade}"),
        Language::English => format!("{decade}s"),
    }
}
